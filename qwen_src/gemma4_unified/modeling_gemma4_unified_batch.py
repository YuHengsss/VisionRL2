@auto_docstring(custom_intro="The base Gemma 4 unified language model without a language modeling head.")
class Gemma4UnifiedTextModel(Gemma4UnifiedPreTrainedModel):
    config: Gemma4UnifiedTextConfig
    input_modalities = ("text",)
    _can_record_outputs = {
        "hidden_states": Gemma4UnifiedTextDecoderLayer,
        "attentions": Gemma4UnifiedTextAttention,
    }

    def __init__(self, config: Gemma4UnifiedTextConfig):
        super().__init__(config)
        self.padding_idx = config.pad_token_id
        self.vocab_size = config.vocab_size

        # Gemma4Unified downcasts the below to bfloat16, causing sqrt(3072)=55.4256 to become 55.5. See https://github.com/huggingface/transformers/pull/29402
        self.embed_tokens = Gemma4UnifiedTextScaledWordEmbedding(
            config.vocab_size, config.hidden_size, self.padding_idx, embed_scale=self.config.hidden_size**0.5
        )
        self.layers = nn.ModuleList(
            [Gemma4UnifiedTextDecoderLayer(config, layer_idx) for layer_idx in range(config.num_hidden_layers)]
        )
        self.norm = Gemma4UnifiedRMSNorm(config.hidden_size, eps=config.rms_norm_eps)
        self.rotary_emb = Gemma4UnifiedTextRotaryEmbedding(config=config)
        self.gradient_checkpointing = False
        self.unique_layer_types = set(self.config.layer_types)

        # ---------------- SD-RPN twig layers (Gemma-4 port) ----------------
        # Convention (stage1, 2026-08-14; K=27 T=3 final):
        #   * twig_K = fork depth: the twig consumes the hidden state OUTPUT
        #     of base layer twig_K-1 (K=27 → fork off L26's output).
        #   * twig slot t is built with layer_idx = twig_K + t — an EXACT
        #     structural clone of base layer twig_K+t. For K=27 T=3 that is
        #     layers 27/28/29 (sliding, sliding, FULL): the twig terminus
        #     aligns with L29, the grounding/pseudo-label layer, and being
        #     global-type gives the RPN q·k map the MQA/512 geometry.
        #     Warm start is a direct state_dict copy. At stage1 sequence
        #     lengths (< sliding_window=1024) sliding and full causal masks
        #     coincide, so pretrained semantics carry over for the sliding
        #     twig slots too.
        #   * The twig is a SIDE BRANCH: the frozen base path still runs all
        #     kept layers (0..29) so the OPL grounding capture at L17/L29
        #     reads the unmodified base attention.
        self.enable_twig = bool(getattr(config, "enable_twig", False))
        self.twig_K = int(getattr(config, "twig_K", 0) or 0)
        self.twig_T = int(getattr(config, "twig_T", 0) or 0)
        self.twig_layers = None
        if self.enable_twig and self.twig_T > 0:
            self.twig_layer_types = [
                config.layer_types[self.twig_K + t] for t in range(self.twig_T)
            ]
            self.twig_layers = nn.ModuleList([
                Gemma4UnifiedTextDecoderLayer(config, layer_idx=self.twig_K + t)
                for t in range(self.twig_T)
            ])

        # ---------------- Need-Refine gate (stage3, qwen high_res port) ----
        # SEPARATE branch (qwen convention: high_res_layers + high_res_head,
        # 38 trained tensors on qwen-7B): forks at the SAME depth as the
        # twig (high_res_K defaults to twig_K=27 → clones of layers
        # 27/28/29, terminus global) + Linear(hidden→1) head. Stateless
        # (no cache writes). Gate pred at inference = sigmoid(head(h[:,-1])).
        self.enable_high_res = bool(getattr(config, "enable_high_res", False))
        self.high_res_K = int(getattr(config, "high_res_K", self.twig_K or 27))
        self.high_res_T = int(getattr(config, "high_res_T", self.twig_T or 3))
        self.high_res_layers = None
        self.high_res_head = None
        if self.enable_high_res and self.high_res_T > 0:
            self.high_res_layer_types = [
                config.layer_types[self.high_res_K + t]
                for t in range(self.high_res_T)
            ]
            self.high_res_layers = nn.ModuleList([
                Gemma4UnifiedTextDecoderLayer(config, layer_idx=self.high_res_K + t)
                for t in range(self.high_res_T)
            ])
            self.high_res_head = nn.Linear(config.hidden_size, 1)

        # ---------------- gate early exit (deployment, 2026-08-25) ---------
        # Plain python attrs (NOT modules/buffers/parameters) so nothing here
        # touches the state_dict or the vision_embedder->embed_vision rename.
        # Armed per pass by roi_inference; module default stays off so every
        # other caller of this class keeps the un-split forward.
        self.gate_early_exit = False
        self._resume_state = None

        # Initialize weights and apply final processing
        self.post_init()

    @merge_with_config_defaults
    @capture_outputs
    @auto_docstring
    def forward(
        self,
        input_ids: torch.LongTensor | None = None,
        attention_mask: torch.Tensor | None = None,
        position_ids: torch.LongTensor | None = None,
        past_key_values: Cache | None = None,
        inputs_embeds: torch.FloatTensor | None = None,
        use_cache: bool | None = None,
        **kwargs: Unpack[TransformersKwargs],
    ) -> Gemma4UnifiedTextModelOutputWithPast:
        if (input_ids is None) ^ (inputs_embeds is not None):
            raise ValueError("You must specify exactly one of input_ids or inputs_embeds")

        if input_ids is not None:
            inputs_embeds = self.embed_tokens(input_ids)

        if use_cache and past_key_values is None:
            past_key_values = DynamicCache(config=self.config)

        if position_ids is None:
            past_seen_tokens = past_key_values.get_seq_length() if past_key_values is not None else 0
            position_ids = torch.arange(inputs_embeds.shape[1], device=inputs_embeds.device) + past_seen_tokens
            position_ids = position_ids.unsqueeze(0)

        # It may already have been prepared by e.g. `generate`
        if not isinstance(causal_mask_mapping := attention_mask, dict):
            # Prepare mask arguments
            mask_kwargs = {
                "config": self.config,
                "inputs_embeds": inputs_embeds,
                "attention_mask": attention_mask,
                "past_key_values": past_key_values,
                "position_ids": position_ids,
            }
            # Create the masks
            causal_mask_mapping = {
                "full_attention": create_causal_mask(**mask_kwargs),
                "sliding_attention": create_sliding_window_causal_mask(**mask_kwargs),
            }

        # embed positions
        hidden_states = inputs_embeds
        position_embeddings = {}
        for layer_type in self.unique_layer_types:
            position_embeddings[layer_type] = self.rotary_emb(hidden_states, position_ids, layer_type)

        # Initialize as empty dict, or reuse past shared states. We use a UserDict instead of built-in dict (it behaves
        # the same) for fsdp2 support (otherwise, `_apply_to_tensors` rebuilds every dict it recurses into, and `shared_kv_states`
        # is not correctly shared, see https://github.com/pytorch/pytorch/blob/v2.10.0/torch/distributed/utils.py#L223-L255)
        shared_kv_states = kwargs.pop("shared_kv_states", UserDict())

        # ---------------- SD-RPN twig fork bookkeeping ----------------
        twig_hidden_states = None
        pre_twig_ctx = None
        high_res_hidden_states = None
        seq_len = hidden_states.shape[1]
        _twig_active = (
            self.enable_twig
            and self.twig_layers is not None
            and self.twig_K > 0
            and seq_len > 1  # prefill only; decode steps don't need a fresh map
        )
        _fork_after = self.twig_K - 1  # fork AFTER base layer twig_K-1
        # Training speedup: layers past max(fork point, deepest OPL capture
        # layer) feed neither the RoI BCE loss nor any gradient path (base is
        # frozen). Skip them. Opt-in default on (SKIP_POST_BRANCH=0 disables).
        _skip_post_branch = (
            (self.training or bool(getattr(self, "_heatmap_only", False)))
            and _twig_active
            and int(os.environ.get("SKIP_POST_BRANCH", "1")) == 1
        )
        _skip_after_layer = self.config.num_hidden_layers - 1
        if _skip_post_branch:
            _max_opl = int(getattr(self.config, "opl_max_layer", -1))
            _skip_after_layer = max(_fork_after, _max_opl)

        # The gate forks at high_res_K-1 and the twig at twig_K-1.  When the
        # gate is at or above the twig, its score exists before the twig would
        # run and the twig can be skipped on samples that will bypass.  Off
        # unless a threshold is supplied, so training is untouched.
        _gate_bypass = False
        _gate_may_skip_twig = (
            (not self.training)
            and self.enable_high_res
            and self.high_res_layers is not None
            and getattr(self, "high_res_head", None) is not None
            and getattr(self, "gate_skip_twig_thresh", None) is not None
            and (self.high_res_K - 1) <= _fork_after
        )

        # ---------------- gate early exit (2026-08-25) ----------------
        # Everything the deployment gate needs — the Need-Refine score and the
        # twig q·k heatmap — is produced at the fork depth (twig_K-1 ==
        # high_res_K-1 == 26 for K=27). Layers 27..47 of pass 1 feed ONLY the
        # pass-1 KV cache and the pass-1 logits, and both are used only on the
        # bypass branch; a fired sample throws the whole pass-1 result away and
        # re-prefills a two-image sequence. So on the fired path those 21
        # layers (43.75% of the stack) are pure waste.
        #
        # With `gate_early_exit` set, the loop stops right after the fork, the
        # partial state is stashed, and the caller decides:
        #   fired  -> discard (compute_rpn_grid only reads twig_hidden_states);
        #   bypass -> resume_after_early_exit(), which runs layers 27..47 with
        #             the SAME hidden state / masks / rope / cache objects, so
        #             the decode path is numerically identical to before.
        # Off by default at module level; the pipeline arms it per sample.
        # A new forward invalidates any stash the caller neither resumed nor
        # discarded (releases its Cache reference instead of leaking it).
        self._resume_state = None
        _early_exit_after = -1
        if (
            (not self.training)
            and getattr(self, "gate_early_exit", False)
            and seq_len > 1
            and (
                _twig_active
                or (self.enable_high_res and self.high_res_layers is not None)
            )
        ):
            # Deepest fork that has to have run before we may stop.
            _early_exit_after = _fork_after if _twig_active else -1
            if self.enable_high_res and self.high_res_layers is not None:
                _early_exit_after = max(_early_exit_after, self.high_res_K - 1)

        # decoder layers
        for i, decoder_layer in enumerate(self.layers[: self.config.num_hidden_layers]):
            hidden_states = decoder_layer(
                hidden_states,
                shared_kv_states=shared_kv_states,
                position_embeddings=position_embeddings[self.config.layer_types[i]],
                attention_mask=causal_mask_mapping[self.config.layer_types[i]],
                position_ids=position_ids,
                past_key_values=past_key_values,
                **kwargs,
            )

            # Need-Refine gate branch: same fork mechanics as the twig,
            # stateless, prefill only. Runs at i == high_res_K-1.
            if (
                self.enable_high_res
                and self.high_res_layers is not None
                and i == self.high_res_K - 1
                and seq_len > 1
            ):
                if _STAGE_TIMING_ON:
                    _t_gate0 = _stage_now()
                gate_hs = hidden_states
                _gate_shared = UserDict()
                for _t, gate_layer in enumerate(self.high_res_layers):
                    _gtype = self.high_res_layer_types[_t]
                    gate_hs = gate_layer(
                        gate_hs,
                        shared_kv_states=_gate_shared,
                        position_embeddings=position_embeddings[_gtype],
                        attention_mask=causal_mask_mapping[_gtype],
                        position_ids=position_ids,
                        past_key_values=None,
                        **kwargs,
                    )
                high_res_hidden_states = gate_hs
                if _STAGE_TIMING_ON:
                    _stage_add("gate_fwd_ms", _stage_now() - _t_gate0)
                # Decide here, while the twig below can still be skipped.
                # Reads the same [:, -1] position the CausalLM wrapper reads,
                # so this decision and the wrapper's cannot disagree; the
                # comparison matches the wrapper's `score <= thresh -> bypass`.
                if _gate_may_skip_twig:
                    with torch.no_grad():
                        _gsc = torch.sigmoid(
                            self.high_res_head(gate_hs[:, -1])
                            .squeeze(-1).float())
                    _gate_bypass = bool(
                        (_gsc <= float(self.gate_skip_twig_thresh)).all())
                # Gate-only training: nothing deeper is needed.
                if self.training and int(os.environ.get("SKIP_POST_BRANCH", "1")) == 1 \
                        and not (self.enable_twig and self.twig_layers is not None):
                    break

            # SD-RPN: fork the twig off the hidden state after layer
            # twig_K-1 (K=27 → L26 output). Each twig layer is a structural
            # clone of base layer twig_K+t and consumes the mask + rope of
            # ITS OWN layer type (identical to full causal at stage1 seq
            # lengths < 1024 for the sliding slots). The twig never touches
            # the main cache (past_key_values=None, private shared_kv dict).
            if _twig_active and i == _fork_after and not _gate_bypass:
                if _STAGE_TIMING_ON:
                    _t_twig0 = _stage_now()
                _last_type = self.twig_layer_types[-1]
                pre_twig_ctx = {
                    # rope/mask of the LAST twig layer's type — consumed by
                    # the RoI q·k scoring in the CausalLM wrapper.
                    "position_embeddings": position_embeddings[_last_type],
                    "attention_mask": causal_mask_mapping[_last_type],
                    "position_ids": position_ids,
                    # RL: everything the frozen reference twig needs to
                    # re-run the twig stack on the same fork input.
                    "hidden_states": hidden_states,
                    "position_embeddings_all": position_embeddings,
                    "attention_mask_all": causal_mask_mapping,
                    "twig_layer_types": list(self.twig_layer_types),
                }
                twig_hs = hidden_states
                _twig_shared = UserDict()
                for _t, twig_layer in enumerate(self.twig_layers):
                    _ttype = self.twig_layer_types[_t]
                    twig_hs = twig_layer(
                        twig_hs,
                        shared_kv_states=_twig_shared,
                        position_embeddings=position_embeddings[_ttype],
                        attention_mask=causal_mask_mapping[_ttype],
                        position_ids=position_ids,
                        past_key_values=None,
                        **kwargs,
                    )
                twig_hidden_states = twig_hs
                if _STAGE_TIMING_ON:
                    _stage_add("twig_fwd_ms", _stage_now() - _t_twig0)

            if _skip_post_branch and i >= _skip_after_layer and twig_hidden_states is not None:
                break

            # Gate early exit: stash everything layers i+1..L-1 would need and
            # hand control back. The final norm is NOT applied (the caller must
            # not read last_hidden_state before resuming) and the lm_head is
            # skipped upstream, so the return costs nothing.
            if _early_exit_after >= 0 and i == _early_exit_after:
                self._resume_state = {
                    "hidden_states": hidden_states,
                    "next_layer": i + 1,
                    "position_embeddings": position_embeddings,
                    "causal_mask_mapping": causal_mask_mapping,
                    "position_ids": position_ids,
                    "past_key_values": past_key_values,
                    "shared_kv_states": shared_kv_states,
                    "kwargs": kwargs,
                }
                return Gemma4UnifiedTextModelOutputWithPast(
                    last_hidden_state=hidden_states,
                    past_key_values=past_key_values,
                    shared_kv_states=(
                        shared_kv_states
                        if kwargs.get("return_shared_kv_states", False)
                        else None
                    ),
                    twig_hidden_states=twig_hidden_states,
                    pre_twig_ctx=pre_twig_ctx,
                    high_res_hidden_states=high_res_hidden_states,
                    early_exited=True,
                )

        hidden_states = self.norm(hidden_states)

        return Gemma4UnifiedTextModelOutputWithPast(
            last_hidden_state=hidden_states,
            past_key_values=past_key_values,
            shared_kv_states=shared_kv_states if kwargs.get("return_shared_kv_states", False) else None,
            twig_hidden_states=twig_hidden_states,
            pre_twig_ctx=pre_twig_ctx,
            high_res_hidden_states=high_res_hidden_states,
        )

    # ------------------------------------------------------------------
    # Gate early exit, second half: run layers next_layer..L-1 on the state
    # stashed by forward(). Byte-for-byte the tail of the original loop —
    # same hidden state tensor, same rope tables, same mask dict, same Cache
    # object, same kwargs — so the resumed pass reproduces the un-split
    # forward exactly (verified 60/60 on docvqa_val + hrbench4k).
    # No twig / gate / OPL branch runs here: both fork at twig_K-1, which is
    # strictly before next_layer.
    # ------------------------------------------------------------------
    def resume_after_early_exit(self) -> Gemma4UnifiedTextModelOutputWithPast:
        st = self._resume_state
        if st is None:
            raise RuntimeError(
                "resume_after_early_exit() called without a stashed early-exit "
                "state (forward() did not early-exit, or it was already "
                "resumed/discarded)")
        self._resume_state = None
        hidden_states = st["hidden_states"]
        position_embeddings = st["position_embeddings"]
        causal_mask_mapping = st["causal_mask_mapping"]
        past_key_values = st["past_key_values"]
        shared_kv_states = st["shared_kv_states"]
        kwargs = st["kwargs"]

        for i in range(int(st["next_layer"]), self.config.num_hidden_layers):
            decoder_layer = self.layers[i]
            hidden_states = decoder_layer(
                hidden_states,
                shared_kv_states=shared_kv_states,
                position_embeddings=position_embeddings[self.config.layer_types[i]],
                attention_mask=causal_mask_mapping[self.config.layer_types[i]],
                position_ids=st["position_ids"],
                past_key_values=past_key_values,
                **kwargs,
            )

        hidden_states = self.norm(hidden_states)

        return Gemma4UnifiedTextModelOutputWithPast(
            last_hidden_state=hidden_states,
            past_key_values=past_key_values,
            shared_kv_states=shared_kv_states if kwargs.get("return_shared_kv_states", False) else None,
            early_exited=False,
        )

    def discard_early_exit_state(self):
        """Fired path: drop the stashed pass-1 tail state (and with it the
        references to the pass-1 cache / masks) without running any layer."""
        self._resume_state = None


@auto_docstring(custom_intro="The base Gemma 4 language model with a language modeling head.")
class Gemma4UnifiedForCausalLM(Gemma4UnifiedPreTrainedModel, GenerationMixin):
    _tied_weights_keys = {"lm_head.weight": "model.embed_tokens.weight"}
    _tp_plan = {"lm_head": "colwise_gather_output"}
