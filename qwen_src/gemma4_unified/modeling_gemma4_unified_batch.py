import time as _stage_time

_STAGE_TIMING_ON = os.environ.get("GEMMA_STAGE_TIMING", "0") == "1"
STAGE_ACC: dict = {}


# Pending (key, start_event, end_event) triples, resolved once per pass by
# _stage_resolve().  Synchronising here instead would drain the pipeline in the
# middle of the layer loop and cost far more than the branch being measured.
STAGE_EVT: list = []


class _StageEvent:
    """A recorded CUDA event; subtracting two of them yields (start, end)."""

    __slots__ = ("ev",)

    def __init__(self):
        self.ev = torch.cuda.Event(enable_timing=True)
        self.ev.record()

    def __sub__(self, other):
        return (other.ev, self.ev)


def _stage_now():
    if torch.cuda.is_available():
        return _StageEvent()
    return _stage_time.perf_counter()


def _stage_add(key: str, dt_seconds):
    if isinstance(dt_seconds, tuple):
        STAGE_EVT.append((key, dt_seconds[0], dt_seconds[1]))
        return
    STAGE_ACC[key] = STAGE_ACC.get(key, 0.0) + dt_seconds * 1000.0


def _stage_resolve():
    """Read the recorded events into STAGE_ACC.  One synchronise, after the
    work, rather than one per mark inside it."""
    if not STAGE_EVT:
        return
    torch.cuda.synchronize()
    for key, ev0, ev1 in STAGE_EVT:
        STAGE_ACC[key] = STAGE_ACC.get(key, 0.0) + ev0.elapsed_time(ev1)
    STAGE_EVT.clear()


